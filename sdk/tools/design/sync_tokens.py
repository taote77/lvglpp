def render_dark_header(document: Dict[str, Any]) -> str:
    lines: List[str] = [
        "#ifndef LVGLPP_COLOR_SHEET_H",
        "#define LVGLPP_COLOR_SHEET_H",
        "",
        "// " + BANNER,
        "// Source: design/tokens.json. Regenerate with:",
        "//   python3 sdk/tools/design/sync_tokens.py generate",
        "",
        "#include <cstdint>",
        "",
        "namespace form::design {",
        "",
        "// ---- colours (dark theme / base values) ----",
    ]
    for name, entry in document["colors"].items():
        value = entry["dark"]
        lines.append(f"inline constexpr std::uint32_t {name} = {cpp_hex(value)}; // {value.upper()}")

    dimensions = document.get("dimensions", {})
    if dimensions:
        lines += ["", "// ---- dimensions (theme independent) ----"]
        for name, value in dimensions.items():
            lines.append(f"inline constexpr std::uint32_t {name} = {value};")

    opacity = document.get("opacity", {})
    if opacity:
        lines += ["", "// ---- opacity ----"]
        for name, value in opacity.items():
            lines.append(f"inline constexpr double {name} = {cpp_number(value)};")

    lines += [
        "",
        "} // namespace form::design",
        "",
        "#endif // LVGLPP_COLOR_SHEET_H",
        "",
    ]
    return "\n".join(lines)


def render_light_header(document: Dict[str, Any]) -> str:
    lines: List[str] = [
        "#ifndef LVGLPP_COLOR_SHEET_LIGHT_H",
        "#define LVGLPP_COLOR_SHEET_LIGHT_H",
        "",
        "// " + BANNER,
        "// Source: design/tokens.json. Tokens without an explicit light value",
        "// reuse the dark-theme value from color_sheet.h.",
        "",
        '#include "color_sheet.h"',
        "",
        "#include <cstdint>",
        "",
        "namespace form::design::light {",
        "",
    ]
    for name, entry in document["colors"].items():
        value = entry.get("light")
        if value is None:
            lines.append(f"inline constexpr std::uint32_t {name} = form::design::{name};")
        else:
            lines.append(f"inline constexpr std::uint32_t {name} = {cpp_hex(value)}; // {value.upper()}")

    lines += [
        "",
        "} // namespace form::design::light",
        "",
        "#endif // LVGLPP_COLOR_SHEET_LIGHT_H",
        "",
    ]
    return "\n".join(lines)


def rendered_outputs(document: Dict[str, Any], dark: Path, light: Path) -> Dict[Path, str]:
    return {
        dark: render_dark_header(document),
        light: render_light_header(document),
    }


def write_outputs(outputs: Dict[Path, str], *, check: bool) -> int:
    stale: List[Path] = []
    for path, text in outputs.items():
        existing = path.read_text(encoding="utf-8") if path.exists() else None
        if existing == text:
            continue
        if check:
            stale.append(path)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {rel(path)}")

    if stale:
        print("stale generated header(s): " + ", ".join(rel(path) for path in stale), file=sys.stderr)
        print("run: python3 sdk/tools/design/sync_tokens.py generate", file=sys.stderr)
        return 1
    if check:
        print("design tokens: generated headers are up to date")
    return 0


