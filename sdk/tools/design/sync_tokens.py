def flatten_tree(
    node: Dict[str, Any],
    prefix: Tuple[str, ...] = (),
    inherited_type: Optional[str] = None,
) -> Dict[Tuple[str, ...], Tuple[Any, Optional[str]]]:
    leaves: Dict[Tuple[str, ...], Tuple[Any, Optional[str]]] = {}
    for key, value in node.items():
        if key.startswith("$") or not isinstance(value, dict):
            continue
        node_type = value.get("$type", inherited_type)
        if "$value" in value:
            leaves[prefix + (key,)] = (value["$value"], node_type)
        else:
            leaves.update(flatten_tree(value, prefix + (key,), node_type))
    return leaves


def find_alias(tree: Dict[str, Any], dotted: str) -> Any:
    node: Any = tree
    for part in dotted.split("."):
        if not isinstance(node, dict) or part not in node:
            return None
        node = node[part]
    if isinstance(node, dict):
        return node.get("$value")
    return None


def resolve_tokens_studio_value(value: Any, tree: Dict[str, Any], depth: int = 0) -> Any:
    if depth > 16:
        return None
    if isinstance(value, str):
        match = ALIAS_RE.match(value.strip())
        if match:
            return resolve_tokens_studio_value(find_alias(tree, match.group(1)), tree, depth + 1)
    return value


def tokens_studio_modes(document: Dict[str, Any], theme_map: Dict[str, str], default_mode: str) -> Dict[str, Dict[str, str]]:
    sets = {key: value for key, value in document.items() if not key.startswith("$") and isinstance(value, dict)}
    themes = document.get("$themes")

    resolved: Dict[str, Dict[str, Any]] = {}
    if isinstance(themes, list) and themes:
        by_figma_name = {value.lower(): key for key, value in theme_map.items()}
        for theme in themes:
            if not isinstance(theme, dict):
                continue
            local_mode = by_figma_name.get(str(theme.get("name", "")).lower())
            if local_mode is None:
                continue
            merged: Dict[str, Any] = {}
            selected = theme.get("selectedTokenSets", {})
            if not isinstance(selected, dict):
                continue
            for set_name, state in selected.items():
                if state in ("source", "enabled") and set_name in sets:
                    merged = deep_merge(merged, sets[set_name])
            resolved[local_mode] = merged
    elif "dark" in sets and "light" in sets:
        shared: Dict[str, Any] = {}
        for name, value in sets.items():
            if name not in MODES:
                shared = deep_merge(shared, value)
        for mode in MODES:
            resolved[mode] = deep_merge(shared, sets[mode])
    else:
        merged = {}
        for value in sets.values():
            merged = deep_merge(merged, value)
        resolved[default_mode] = merged

    modes: Dict[str, Dict[str, str]] = {}
    for mode, tree in resolved.items():
        leaves = flatten_tree(tree)
        colors: Dict[str, str] = {}
        for path, (raw_value, value_type) in leaves.items():
            value = resolve_tokens_studio_value(raw_value, tree)
            if value is None:
                continue
            hex_value = color_to_hex(value, source=".".join(path))
            if hex_value is None:
                continue
            if value_type is not None and str(value_type).lower() != "color":
                # Some exports omit $type on groups; a parseable colour wins.
                if not isinstance(value, str) or not value.strip().startswith("#"):
                    continue
            colors[normalize_path(".".join(path))] = hex_value
        modes[mode] = colors
    return modes


