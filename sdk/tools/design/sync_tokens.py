def load_tokens(path: Path) -> Dict[str, Any]:
    try:
        document = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        fail(f"token file not found: {rel(path)}")
    except json.JSONDecodeError as exc:
        fail(f"{rel(path)}: {exc}")

    validate_tokens(document, path)
    return document


def validate_tokens(document: Dict[str, Any], path: Path) -> None:
    if not isinstance(document, dict):
        fail(f"{rel(path)}: top level must be an object")
    if document.get("version") != 1:
        fail(f"{rel(path)}: unsupported version {document.get('version')!r} (expected 1)")

    colors = document.get("colors")
    dimensions = document.get("dimensions", {})
    opacity = document.get("opacity", {})

    if not isinstance(colors, dict) or not colors:
        fail(f"{rel(path)}: 'colors' must be a non-empty object")
    if not isinstance(dimensions, dict):
        fail(f"{rel(path)}: 'dimensions' must be an object")
    if not isinstance(opacity, dict):
        fail(f"{rel(path)}: 'opacity' must be an object")

    seen: Set[str] = set()
    for section_name, section in (("colors", colors), ("dimensions", dimensions), ("opacity", opacity)):
        for name, entry in section.items():
            if name in seen:
                fail(f"{rel(path)}: duplicate token name {name}")
            seen.add(name)
            if not IDENT_RE.match(name):
                fail(f"{rel(path)}: invalid token name {name!r} (use UPPER_SNAKE_CASE)")

            if section_name == "colors":
                if not isinstance(entry, dict):
                    fail(f"{rel(path)}: colors.{name} must be an object")
                dark = entry.get("dark")
                light = entry.get("light")
                for mode, value in (("dark", dark), ("light", light)):
                    if value is None:
                        continue
                    if color_to_hex(value, source=name) is None:
                        fail(f"{rel(path)}: colors.{name}.{mode} is not a colour: {value!r}")
                if dark is None:
                    fail(f"{rel(path)}: colors.{name} needs a 'dark' value")
                if "figma" in entry and not isinstance(entry["figma"], str):
                    fail(f"{rel(path)}: colors.{name}.figma must be a string")
            elif section_name == "dimensions":
                if not isinstance(entry, int) or isinstance(entry, bool) or entry < 0:
                    fail(f"{rel(path)}: dimensions.{name} must be a non-negative integer")
            else:
                if not isinstance(entry, (int, float)) or isinstance(entry, bool) or not 0 <= entry <= 1:
                    fail(f"{rel(path)}: opacity.{name} must be between 0 and 1")


