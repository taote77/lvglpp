#!/usr/bin/env python3
"""Design-token import and C++ header generator for LVGL++.

`design/tokens.json` is the local source of truth. This tool can:

  * import a Figma export (Tokens Studio JSON or Figma Variables JSON),
  * pull Figma Variables through the REST API (Enterprise plans),
  * generate the C++ headers used by the SDK and smart_home,
  * verify that the committed headers are up to date (`--check`).

Only the Python standard library is used so the tool also works in minimal
build containers.
"""

from __future__ import annotations

import argparse
import datetime
import json
import os
import re
import sys
import urllib.error
import urllib.request
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional, Set, Tuple

REPO_ROOT = Path(__file__).resolve().parents[3]
DEFAULT_TOKENS = REPO_ROOT / "design" / "tokens.json"
DEFAULT_DARK_HEADER = REPO_ROOT / "sdk" / "config" / "color_sheet.h"
DEFAULT_LIGHT_HEADER = REPO_ROOT / "sdk" / "config" / "color_sheet_light.h"

BANNER = "Generated by sdk/tools/design/sync_tokens.py. Do not edit by hand."

COLOR_RE = re.compile(r"^#[0-9A-Fa-f]{3}(?:[0-9A-Fa-f]{3}){0,2}$")
IDENT_RE = re.compile(r"^[A-Z][A-Z0-9_]*$")
ALIAS_RE = re.compile(r"^\{\s*([^{}]+?)\s*\}$")
RGBA_RE = re.compile(r"^rgba?\(([^)]*)\)$", re.IGNORECASE)

MODES = ("dark", "light")


# ---------------------------------------------------------------------------
# small helpers
# ---------------------------------------------------------------------------


def warn(message: str) -> None:
    print("warning: " + message, file=sys.stderr)


def fail(message: str) -> "NoReturn":  # type: ignore[name-defined]
    print("error: " + message, file=sys.stderr)
    raise SystemExit(1)


def rel(path: Path) -> str:
    try:
        return str(path.relative_to(REPO_ROOT))
    except ValueError:
        return str(path)


def normalize_path(value: str) -> str:
    """Normalise a Figma/token path for fuzzy matching.

    ``Color/Brand.Primary`` and ``color.brand.primary`` both become
    ``color/brand/primary``.
    """
    parts = re.findall(r"[a-z0-9]+", value.lower())
    return "/".join(parts)


def color_to_hex(value: Any, *, source: str = "") -> Optional[str]:
    """Convert a Tokens Studio colour value to ``#RRGGBB``."""
    if isinstance(value, str):
        text = value.strip()
        match = COLOR_RE.match(text)
        if match:
            digits = text[1:]
            if len(digits) == 3:
                digits = "".join(ch * 2 for ch in digits)
            if len(digits) == 8 and digits[6:].upper() != "FF":
                warn(f"alpha channel is not supported by LVGL colour tokens ({source or text})")
            return "#" + digits[:6].upper()

        match = RGBA_RE.match(text)
        if match:
            channels = [part.strip() for part in match.group(1).split(",")]
            if len(channels) not in (3, 4):
                return None
            values: List[int] = []
            for channel in channels[:3]:
                try:
                    number = float(channel.rstrip("%"))
                except ValueError:
                    return None
                if channel.endswith("%"):
                    number = number * 255.0 / 100.0
                values.append(max(0, min(255, int(round(number)))))
            return "#{:02X}{:02X}{:02X}".format(*values)
    return None


def rgb_floats_to_hex(value: Dict[str, Any]) -> Optional[str]:
    try:
        channels = [value["r"], value["g"], value["b"]]
    except KeyError:
        return None
    values = [max(0, min(255, int(round(float(channel) * 255.0)))) for channel in channels]
    return "#{:02X}{:02X}{:02X}".format(*values)


def cpp_hex(value: str) -> str:
    return "0x" + value.lstrip("#").upper()


def cpp_number(value: Any) -> str:
    if isinstance(value, bool):
        fail("boolean values are not valid design dimensions")
    if isinstance(value, int):
        return str(value)
    text = f"{float(value):.4f}".rstrip("0")
    if text.endswith("."):
        text += "0"
    return text


def deep_merge(base: Dict[str, Any], override: Dict[str, Any]) -> Dict[str, Any]:
    merged = dict(base)
    for key, value in override.items():
        if isinstance(value, dict) and isinstance(merged.get(key), dict):
            merged[key] = deep_merge(merged[key], value)
        else:
            merged[key] = value
    return merged


