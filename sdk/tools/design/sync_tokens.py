def figma_variables_root(document: Dict[str, Any]) -> Optional[Tuple[Dict[str, Any], Dict[str, Any]]]:
    meta = document.get("meta") if isinstance(document.get("meta"), dict) else document
    variables = meta.get("variables")
    collections = meta.get("variableCollections")
    if isinstance(variables, dict) and isinstance(collections, dict):
        return variables, collections
    return None


def resolve_figma_color(
    variable: Dict[str, Any],
    mode_name: str,
    variables: Dict[str, Any],
    collections: Dict[str, Any],
    depth: int = 0,
) -> Optional[str]:
    if depth > 16:
        return None
    collection = collections.get(variable.get("variableCollectionId"), {})
    mode_id = None
    for mode in collection.get("modes", []):
        if str(mode.get("name", "")).lower() == mode_name.lower():
            mode_id = mode.get("modeId")
            break
    if mode_id is None:
        return None

    value = variable.get("valuesByMode", {}).get(mode_id)
    if value is None:
        return None

    if isinstance(value, dict):
        if value.get("type") == "VARIABLE_ALIAS" or ("id" in value and "r" not in value):
            target = variables.get(value.get("id"))
            if not isinstance(target, dict):
                return None
            return resolve_figma_color(target, mode_name, variables, collections, depth + 1)
        return rgb_floats_to_hex(value)

    if isinstance(value, str):
        return color_to_hex(value)
    return None


def figma_variable_modes(document: Dict[str, Any], theme_map: Dict[str, str]) -> Dict[str, Dict[str, str]]:
    root = figma_variables_root(document)
    if root is None:
        fail("not a Figma Variables export (missing meta.variables/meta.variableCollections)")
    variables, collections = root

    modes: Dict[str, Dict[str, str]] = {}
    for local_mode, figma_mode in theme_map.items():
        colors: Dict[str, str] = {}
        for variable in variables.values():
            if not isinstance(variable, dict) or variable.get("resolvedType") != "COLOR":
                continue
            hex_value = resolve_figma_color(variable, figma_mode, variables, collections)
            if hex_value is not None:
                colors[normalize_path(str(variable.get("name", "")))] = hex_value
        if colors:
            modes[local_mode] = colors
        else:
            warn(f"no Figma colour variables found for mode {figma_mode!r}")
    return modes


# ---------------------------------------------------------------------------
# applying an imported mode map
# ---------------------------------------------------------------------------


def local_candidates(name: str, entry: Dict[str, Any]) -> Set[str]:
    figma = entry.get("figma")
    if isinstance(figma, str) and figma.strip():
        return {normalize_path(figma)}
    stem = name[4:] if name.startswith("CLR_") else name
    return {normalize_path(stem)}


def match_local_tokens(path: str, colors: Dict[str, Any]) -> List[str]:
    normalized = normalize_path(path)
    exact = [name for name, entry in colors.items() if normalized in local_candidates(name, entry)]
    if exact:
        return exact

    # Allow a Figma group prefix (e.g. "color/brand") or a local semantic
    # prefix. Ambiguous matches are reported instead of guessed.
    matches: List[str] = []
    for name, entry in colors.items():
        for candidate in local_candidates(name, entry):
            if not candidate:
                continue
            if normalized.endswith("/" + candidate) or candidate.endswith("/" + normalized):
                matches.append(name)
                break
    return matches


def apply_modes(
    document: Dict[str, Any],
    modes: Dict[str, Dict[str, str]],
    *,
    add_missing: bool,
    dry_run: bool,
) -> int:
    colors = document["colors"]
    changes = 0
    unmatched: Dict[str, Set[str]] = {}
    ambiguous: List[str] = []

    for mode in MODES:
        imported = modes.get(mode)
        if not imported:
            continue
        for path in sorted(imported):
            value = imported[path]
            matches = match_local_tokens(path, colors)
            if len(matches) > 1:
                ambiguous.append(f"{path} ({mode}) matches {', '.join(sorted(matches))}")
                continue
            if not matches:
                unmatched.setdefault(path, set()).add(mode)
                continue
            name = matches[0]
            if colors[name].get(mode) != value:
                print(f"  {name} [{mode}]: {colors[name].get(mode, '-')} -> {value}")
                colors[name][mode] = value
                changes += 1

    if add_missing:
        for path in sorted(unmatched):
            parts = [part for part in path.split("/") if part]
            if parts and parts[0] in ("color", "colors", "colour", "colours"):
                parts = parts[1:]
            name = "CLR_" + "_".join(part.upper() for part in parts)
            if not IDENT_RE.match(name):
                warn(f"cannot derive a C++ token name from {path!r}")
                continue
            if name in colors:
                ambiguous.append(f"{path} would add {name}, which already exists")
                continue
            entry: Dict[str, Any] = {"figma": path}
            for mode in sorted(unmatched[path]):
                value = modes.get(mode, {}).get(path)
                if value:
                    entry[mode] = value
            if "dark" not in entry:
                warn(f"skipping {path!r}: no dark-mode value")
                continue
            colors[name] = entry
            print(f"  added {name} from {path}")
            changes += 1
        unmatched = {}

    for message in ambiguous:
        warn("ambiguous token: " + message)
    if unmatched:
        warn(f"{len(unmatched)} imported colour token(s) did not match a local token")
        for path in sorted(unmatched)[:12]:
            print(f"  unmatched: {path} ({', '.join(sorted(unmatched[path]))})", file=sys.stderr)

    if dry_run:
        print(f"dry run: {changes} change(s), nothing written")
    return changes


