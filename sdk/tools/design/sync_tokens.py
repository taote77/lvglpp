def parse_theme_map(value: Optional[str], document: Dict[str, Any]) -> Dict[str, str]:
    if value is None:
        configured = document.get("meta", {}).get("figma", {}).get("themeMap")
        if isinstance(configured, dict):
            return {str(key): str(mode) for key, mode in configured.items()}
        return {"dark": "Dark", "light": "Light"}

    result = {"dark": "Dark", "light": "Light"}
    for pair in value.split(","):
        pair = pair.strip()
        if not pair:
            continue
        if "=" not in pair:
            fail(f"invalid --theme-map entry {pair!r} (expected local=Remote)")
        local, remote = (part.strip() for part in pair.split("=", 1))
        if local not in MODES:
            fail(f"unknown local theme {local!r} (expected dark or light)")
        result[local] = remote
    return result


def save_tokens(document: Dict[str, Any], path: Path) -> None:
    document.setdefault("meta", {}).setdefault("figma", {})["lastSyncedAt"] = (
        datetime.datetime.now(datetime.timezone.utc).replace(microsecond=0).isoformat()
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(document, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"updated {rel(path)}")


def import_document(
    document: Dict[str, Any],
    export: Dict[str, Any],
    *,
    theme_map: Dict[str, str],
    default_mode: str,
    add_missing: bool,
    dry_run: bool,
) -> int:
    if figma_variables_root(export) is not None:
        modes = figma_variable_modes(export, theme_map)
        source = "Figma Variables"
    elif isinstance(export.get("$themes"), list) or any(
        isinstance(value, dict) and not key.startswith("$") for key, value in export.items()
    ):
        modes = tokens_studio_modes(export, theme_map, default_mode)
        source = "Tokens Studio"
    else:
        fail("unrecognised export format (expected Tokens Studio or Figma Variables JSON)")

    found = {mode: len(values) for mode, values in modes.items()}
    print(f"imported {source}: " + ", ".join(f"{mode}={count}" for mode, count in found.items()))
    if not modes:
        fail("no colour tokens found in the export")

    changes = apply_modes(document, modes, add_missing=add_missing, dry_run=dry_run)
    if changes == 0:
        print("design tokens already up to date")
    return changes


def command_generate(args: argparse.Namespace) -> int:
    document = load_tokens(args.tokens)
    outputs = rendered_outputs(document, args.header, args.light_header)
    return write_outputs(outputs, check=args.check)


def command_import(args: argparse.Namespace) -> int:
    document = load_tokens(args.tokens)
    try:
        export = json.loads(Path(args.export).read_text(encoding="utf-8"))
    except FileNotFoundError:
        fail(f"export not found: {args.export}")
    except json.JSONDecodeError as exc:
        fail(f"{args.export}: {exc}")

    theme_map = parse_theme_map(args.theme_map, document)
    changes = import_document(
        document,
        export,
        theme_map=theme_map,
        default_mode=args.theme,
        add_missing=args.add,
        dry_run=args.dry_run,
    )
    if changes and not args.dry_run:
        save_tokens(document, args.tokens)
        outputs = rendered_outputs(document, args.header, args.light_header)
        write_outputs(outputs, check=False)
    return 0


def command_fetch(args: argparse.Namespace) -> int:
    document = load_tokens(args.tokens)
    file_key = args.file_key or document.get("meta", {}).get("figma", {}).get("fileKey")
    if not file_key:
        fail("no Figma file key: pass --file-key or set meta.figma.fileKey")

    token = os.environ.get(args.token_env)
    if not token:
        fail(f"environment variable {args.token_env} is not set")

    export = fetch_figma_variables(file_key, token)
    if args.save_raw:
        raw_path = Path(args.save_raw)
        raw_path.parent.mkdir(parents=True, exist_ok=True)
        raw_path.write_text(json.dumps(export, indent=2) + "\n", encoding="utf-8")
        print(f"wrote raw export to {args.save_raw}")

    theme_map = parse_theme_map(args.theme_map, document)
    changes = import_document(
        document,
        export,
        theme_map=theme_map,
        default_mode="dark",
        add_missing=args.add,
        dry_run=args.dry_run,
    )
    if changes and not args.dry_run:
        document.setdefault("meta", {}).setdefault("figma", {})["fileKey"] = file_key
        save_tokens(document, args.tokens)
        outputs = rendered_outputs(document, args.header, args.light_header)
        write_outputs(outputs, check=False)
    return 0


def add_common_paths(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("--tokens", type=Path, default=DEFAULT_TOKENS, help="local token file")
    parser.add_argument("--header", type=Path, default=DEFAULT_DARK_HEADER, help="generated dark header")
    parser.add_argument("--light-header", type=Path, default=DEFAULT_LIGHT_HEADER, help="generated light header")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)

    generate = sub.add_parser("generate", help="generate C++ headers from design/tokens.json")
    add_common_paths(generate)
    generate.add_argument("--check", action="store_true", help="fail when generated headers are stale")
    generate.set_defaults(func=command_generate)

    for name, help_text, func in (
        ("import", "import a Tokens Studio or Figma Variables JSON export", command_import),
        ("fetch", "pull Figma Variables through the REST API", command_fetch),
    ):
        sub_parser = sub.add_parser(name, help=help_text)
        add_common_paths(sub_parser)
        if name == "import":
            sub_parser.add_argument("export", help="exported JSON file")
        else:
            sub_parser.add_argument("--file-key", help="Figma file key (defaults to meta.figma.fileKey)")
            sub_parser.add_argument("--token-env", default="FIGMA_TOKEN", help="env var holding the Figma token")
            sub_parser.add_argument("--save-raw", help="write the raw API response to this path")
        sub_parser.add_argument("--theme-map", help="local=Remote mode names, e.g. dark=Dark,light=Light")
        sub_parser.add_argument("--add", action="store_true", help="add unmatched tokens as CLR_* entries")
        sub_parser.add_argument("--dry-run", action="store_true", help="print changes without writing files")
        if name == "import":
            sub_parser.add_argument(
                "--theme", default="dark", choices=MODES, help="target mode for single-set exports"
            )
        sub_parser.set_defaults(func=func)

    return parser


def main(argv: Optional[Iterable[str]] = None) -> int:
    parser = build_parser()
    args = parser.parse_args(list(argv) if argv is not None else None)
    return int(args.func(args))


if __name__ == "__main__":
    sys.exit(main())
