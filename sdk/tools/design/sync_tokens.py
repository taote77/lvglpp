def fetch_figma_variables(file_key: str, token: str) -> Dict[str, Any]:
    url = f"https://api.figma.com/v1/files/{file_key}/variables/local"
    request = urllib.request.Request(
        url,
        headers={
            "X-Figma-Token": token,
            "User-Agent": "lvglpp-design-sync/1",
        },
    )
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            return json.loads(response.read().decode("utf-8"))
    except urllib.error.HTTPError as exc:
        hint = " (the Variables REST API requires a Figma Enterprise plan)" if exc.code in (403, 404) else ""
        fail(f"Figma API returned HTTP {exc.code}{hint}")
    except urllib.error.URLError as exc:
        fail(f"could not reach the Figma API: {exc.reason}")
    return {}


